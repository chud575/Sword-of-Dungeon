// humans: the SIX trained fighters of the human family, drawn as HD-2D pixel sprites in the one
// house style (sprites/style.js) — dwarven guard, mercenary, swordsman, monk, dark warrior and the
// War Lord. Every one of them is a real MONSTER_TABLE type; nothing fictional is drawn here.
//
// THE SIX WERE ONE MANNEQUIN RECOLOURED. Every one of them built at 48x48 on pivot (24,45) with
// the same shoulder line, the same head block and the same sword diagonal, so the blue mercenary
// and the brown swordsman were literally the same person in different paint — and two of them were
// blockout-quality next to the creature art: the swordsman was a blue noodle with a stick, the monk
// an unreadable brown blob. They are now differentiated by SILHOUETTE, and the test is the only one
// that counts: render each of them filled solid black and name it. All six pass.
//
//   dwarven guard  THREE TIERS no man can make: a DOMED war helm — a rounded skull, a brow band and
//                  a 20-px brim with the ends turned down into cheek plates — over a forked beard of
//                  18 over a body of 14. Wide, wide, narrow, top to bottom. No face under the brim,
//                  only two catch-lights and a nasal bar; a bearded axe hanging on the off side.
//   mercenary      the ASYMMETRIC one: one strapped pauldron on the sword shoulder, a round buckler
//                  breaking the outline as a disc on the other arm, a plain sword hanging point-down
//                  clear of his leg, and bare legs below a jerkin cut into tabs.
//   swordsman      the LONG COAT, and the only SPLIT hem: a narrow column that bells out below the
//                  belt and then parts into two tapering panels with the boots walking out of the
//                  gap, a leather-faced placket and three brass buttons up the front, and the long
//                  slim blade held LOW, outside the silhouette from grip to point.
//   monk           the only NECK in the cast — a shaved skull on three pixels of bare throat — and
//                  the only free-standing vertical: a quarterstaff PLANTED (its ferrule pinned to
//                  the pivot row whatever the body does above it) and rising past his head, three
//                  columns clear of the robe. Barefoot, a rust stole from shoulder to hip, nothing
//                  strapped or spiked. The calmest outline in the game.
//   dark warrior   TALL AND HORNED: two horns tapering to a point as they sweep up and OUT from a
//                  closed sallet, so the top of his silhouette is the only V in the cast; spiked
//                  pauldrons wider than his stance over a chest that wedges to the belt, and a cloak
//                  widening the base so the wedge stands on a triangle. Two ember slits.
//   war lord       the heaviest human silhouette in the game, and the only one on a bigger canvas:
//                  a crimson plume over a gold-banded helm, pauldrons past his stance, a cape to the
//                  floor and a two-handed greatsword rising clear past his own shoulder.
//
// WHAT MAKES A SILHOUETTE READ, learned the hard way in this file:
//  1. A WEAPON DRAWN INSIDE THE BODY IS NOT IN THE SILHOUETTE. Four of the six carried their blade
//     over their own chest, where a solid-black test sees nothing. Every weapon here now leaves the
//     outline: the swordsman's point falls into empty air, the monk's staff is a separate column,
//     the dark warrior's blade crosses air past his shoulder.
//  2. TWO PIXELS OF AIR IS ONE PIXEL TOO FEW. The house ink is 1 px on each side, so a 2-px gap
//     between two forms closes into solid ink and the two become one blob. Anything meant to read
//     as separate — a staff beside a robe, a horn beside a helm — needs THREE.
//  3. NOTHING ENDS ON A RULED LINE. Every hem here is arched, lobed, split or cut into tabs.
//  4. TWO ROBES ARE ONE ROBE. The monk and the swordsman were both bells, and a bell is a bell
//     whatever colour it is painted; the swordsman's hem had to SPLIT and his front had to grow a
//     placket before the two could be told apart across a room.
//  5. HOUSE INK BELONGS ON THE OUTSIDE. `houseOutline` keeps interior ink as drawing — correctly —
//     so a sleeve that arrives carrying its own black ring scribbles that ring across the chest it
//     lies on. `limbPix(..., { edge })` outlines an arm in one step of the GARMENT's own ramp
//     instead: cloth on cloth, plate on plate, ink only where the figure meets the air.
//
// TWO CANVASES, ONE PIXEL DENSITY
//   MAN   48x48, pivot (24,45) — the five ordinary fighters, figures 35-44 px.
//   LORD  64x72, pivot (32,68) — the War Lord alone, figure 67 px.
// style.js SCALE says how tall each creature stands relative to the hero and `sizeFor` turns that
// into the billboard multiplier; drawing the War Lord at 66 px instead of squeezing him onto the
// 40-px canvas the other humans use is what keeps his texels the same size as everyone else's
// (0.86x) instead of double-size mush (2.11x). Every figure here lands in a 0.86-1.19 band.
//
// SHARED KEY VOCABULARY (identical to humanoid.js, so the two files read as one cast):
//   # outline (house INK)   @ lit edge      1 2 3 skin dark->light
//   7 4 5 6 cloth (7 = darkest crease)      8 9 0 leather      a b c d metal (+d specular)
//   e f g accent            T bone   E eye socket   W eye catch-light   Y glow (emissive)
//   G glint (emissive)      F hurt flash
// Ramps come from style.ramp(): shadows drift violet and gain saturation, highlights drift amber
// and lose a little. The key light is TOP-LEFT on every facing. Bodies are drawn WITHOUT their
// outline and inked by `ink()` afterwards, so the silhouette is exactly one pixel everywhere and
// softens to '@' on the edges that face the light.
//
// SHAPE FIRST, SHADING SECOND — WITH ONE EXCEPTION. Cloth blocks (the coat, the robe, the hauberk)
// are typed as FLAT shapes in one key and re-lit by `keyed()` (pixelPainter.keyShade) off the house
// top-left terminator: hand-typing a value into every pixel of a 22-px-wide coat is how the old art
// ended up pillow-shaded and how rows ended up the wrong width. But `keyShade` RE-KEYS every pixel
// holding one of the ramp keys it is given, so structure drawn in those keys is erased — a coat's
// front edge typed in '7' simply disappears. Two consequences, both used here: structure inside a
// re-lit block is drawn in a DIFFERENT vocabulary (the swordsman's placket in leather, his buttons
// and the monk's stole in accent), and the Dark Warrior's plate — which is all structure and no
// cloth — is hand-valued with `body()` instead, one lit pixel of the top step down every top-left
// facing edge and the ramp running left to right across the form.
//
// FACINGS south / east / north are each drawn; west is the mirrored east.
// CLIPS idle(4) walk(6) attack(4) hurt(2) death(5).
