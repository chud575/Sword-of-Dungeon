/**
 * Bare feet under the robe. The shared boot block is repainted skin (`BAREFOOT`) and then SHAVED:
 * the outermost fill pixel of every run in the bottom four rows comes off, which takes the cuff
 * and the sole overhang away and leaves a narrow foot. A recolour on its own left the monk in
 * flesh-coloured BOOTS, which is worse than leaving them brown.
 */
const BAREFOOT = { 7: '1', 8: '1', 9: '2', 0: '3', s: '1' };
function shaveBoot(p, rows = 4) {
  const o = clone(p);
  for (let y = p.h - rows; y < p.h; y++) {
    for (let x = 0; x < p.w; x++) {
      if (!p.d[y * p.w + x]) continue;
      let x1 = x; while (x1 + 1 < p.w && p.d[y * p.w + x1 + 1]) x1++;
      if (x1 - x >= 4) { o.d[y * p.w + x] = 0; o.d[y * p.w + x1] = 0; }
      x = x1;
    }
  }
  return o;
}
const barefoot = (set) => Object.fromEntries(Object.entries(set).map(([k, p]) => [k, shaveBoot(recolor(p, BAREFOOT))]));

