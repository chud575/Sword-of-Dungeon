/** Map a humanoid.js rig point (on its 40x40, pivot (20,37) canvas) onto a geometry. */
const rigPt = (G, x, y) => [Math.round(G.px + (x - 20) * G.k), Math.round(G.py + (y - 37) * G.k)];

// ------------------------------------------------------------------------------------ palette
// `ramp()` builds seven house steps; each vocabulary picks the ones it needs so a 3-key ramp is a
// slice of the same curve as a 4-key one and every species shares one contrast law.
// The house hue-shift is deliberately strong; over a SEVEN step ramp it will walk an olive all the
// way round to green, so the shift is dialled to the same figure the shipping cast uses (0.02) and
// each vocabulary takes the slice of the curve its material actually occupies: cloth and skin live
// in the middle (they are dyed and pigmented, not polished), metal reaches the top because a
// specular highlight is the whole point of steel, and leather sits between them.
const RAMP_OPTS = { hueShift: 0.02, satShift: 0.06 };
const RAMP_PICK = { skin: [1, 3, 5], cloth: [0, 2, 3, 4], leather: [1, 3, 4], metal: [1, 3, 5, 6], accent: [1, 3, 5] };

/**
 * One species palette over the shared key vocabulary. `picks` overrides which steps of the
 * seven-step house ramp a material takes — the Dark Warrior's plate is the same curve as the
 * Swordsman's, read from four steps lower down.
 * @param {{skin:string, cloth:string, leather:string, metal:string, accent:string, eye:string,
 *   tooth?:string, picks?:Object<string, number[]>}} o
 */
export function humanPalette(o) {
  const p = new Palette().set('#', INK).set('@', INK_LIT);
  const put = (keys, base, which) => {
    const r = ramp(base, 7, RAMP_OPTS);
    const pick = (o.picks && o.picks[which]) || RAMP_PICK[which];
    [...keys].forEach((k, i) => p.set(k, r[pick[i]]));
  };
  put('123', o.skin, 'skin');
  put('7456', o.cloth, 'cloth');   // 7 is the darkest crease, then 4 5 6 up to the lit fold
  put('890', o.leather, 'leather');
  // `s` is THE SOLE: the bottom step of the leather ramp, one below the darkest boot tone, so the
  // last row of every boot is in true contact shadow instead of borrowing the trouser colour.
  p.set('s', ramp(o.leather, 7, RAMP_OPTS)[0]);
  put('abcd', o.metal, 'metal');   // d is a 1-px specular only
  put('efg', o.accent, 'accent');
  return p
    .set('T', o.tooth || '#ded2b8')
    .set('E', '#191322')
    .set('W', '#e6dcc8')
    .set('Y', o.eye)
    .set('G', '#efe9dd')
    .set('F', '#fff4f0');
}

// ------------------------------------------------------------------------------------ inking
const LIGHT_KEYS = new Set(['3', '6', '0', 'c', 'd', 'g', 'T', 'W'].map((c) => c.charCodeAt(0)));

/** Ink a hand-drawn body part: one-pixel house outline, softened to '@' on the lit edges. */
const ink = (p) => outline(p, '#', { lit: LIT, litKey: '@' });
/** Ink a block written as rows of keys (no outline characters in the source art). */
const body = (rows) => ink(paint(rows));
/**
 * The same, but RE-SHADED to the house key light first (pixelPainter.keyShade): the pixels holding
 * `keys` are re-keyed off a top-left terminator — highlight on the upper-left third, core shadow on
 * the lower-right third, reflected light as one cooler pixel on the bottom-right rim. Use it on any
 * block whose hand-typed shading rings the form (dark at BOTH edges, bright down the middle), which
 * is pillow shading and is banned by style.js.
 */
const keyed = (rows, keys, o = {}) => ink(keyShade(paint(rows), keys, { lit: LIT, ...o }));

/** Soften a composed frame's remaining hard outline where a light tone meets empty space top-left. */
function softenLit(p) {
  const o = { w: p.w, h: p.h, d: new Uint16Array(p.d) };
  const HASH = 35, AT = 64;
  for (let y = 0; y < p.h; y++) for (let x = 0; x < p.w; x++) {
    if (p.d[y * p.w + x] !== HASH) continue;
    const inR = x + 1 < p.w ? p.d[y * p.w + x + 1] : 0, inD = y + 1 < p.h ? p.d[(y + 1) * p.w + x] : 0;
    const outL = x > 0 ? p.d[y * p.w + x - 1] : 0, outU = y > 0 ? p.d[(y - 1) * p.w + x] : 0;
    if ((LIGHT_KEYS.has(inR) && !outL) || (LIGHT_KEYS.has(inD) && !outU)) o.d[y * p.w + x] = AT;
  }
  return o;
}

